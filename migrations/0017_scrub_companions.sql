-- لا يُستعمل صحابي شخصيةً في اللعبة. تقارير النصب القديمة كانت تقول «وشاعرها حسان بن ثابت»
-- أو «كعب بن مالك»؛ نستبدل الاسمين في النص المخزَّن بالشاعرين المعتمدين في gdd.md §7.
-- هذا الملف وحده مستثنى من حارس المحتوى (content.test.ts)، ولا يستعمل الاسمين إلا هنا في الاستبدال.

update reports
set body = replace(body, 'حسان بن ثابت', 'أحيحة بن الجلاح (سيد الأوس في الجاهلية)')
where body like '%حسان بن ثابت%';

update reports
set body = replace(body, 'كعب بن مالك', 'حادي تهامة (شخصية متخيَّلة)')
where body like '%كعب بن مالك%';

update reports
set title = replace(replace(title, 'حسان بن ثابت', 'أحيحة بن الجلاح'), 'كعب بن مالك', 'حادي تهامة')
where title like '%حسان بن ثابت%' or title like '%كعب بن مالك%';
